export function detectLang() {
  try {
    const saved = localStorage.getItem("lang");
    if (saved && LANGS.includes(saved)) return saved;
  } catch {}
  return (navigator.language || "").toLowerCase().startsWith("ko") ? "ko" : "en";
}
